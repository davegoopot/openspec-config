import { execFileSync } from 'node:child_process';
import { chmodSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

export const PKG_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const REPO_URL = 'https://github.com/davegoopot/openspec-config';
const GENERATED_HEADER_RE = /^# Generated by openspec-config@/;
const OVERRIDE_NAMES = ['config.override.yaml', 'config.override.yml'];
const TOP_ORDER = ['schema', 'store', 'references', 'context', 'rules', 'operations', 'githubCopilot'];

export function isPlainObject(v) {
  return v !== null && typeof v === 'object' && !Array.isArray(v);
}

/**
 * Merge a base config with a per-repo override.
 * - Nested maps deep-merge.
 * - Scalars and arrays REPLACE the base value at the deepest key provided.
 * - Setting a key to null in the override DELETES it from the base.
 */
export function mergeConfigs(base = {}, override = {}) {
  if (!isPlainObject(base) || !isPlainObject(override)) {
    throw new Error('config documents must be YAML mappings');
  }
  const out = { ...base };
  for (const [k, v] of Object.entries(override)) {
    if (v === null) {
      delete out[k];
    } else if (isPlainObject(v) && isPlainObject(out[k])) {
      out[k] = mergeConfigs(out[k], v);
    } else {
      out[k] = v;
    }
  }
  return out;
}

function isPlainSafeScalar(s) {
  if (s === '' || /^[ \t]/.test(s) || /[ \t]$/.test(s) || /[\n\r]/.test(s)) return false;
  if (/^(true|false|null|yes|no|on|off|~)$/i.test(s)) return false;
  if (/^[-?:,[\]{}#&*!|>'"%@`]/.test(s)) return false;
  if (/:( |$)/.test(s) || / #/.test(s)) return false;
  if (/^[-+]?(\d+\.?\d*|\.\d+)([eE][-+]?\d+)?$/.test(s)) return false;
  if (/^0x[0-9a-f]+$/i.test(s)) return false;
  if (/^\d{4}-\d{1,2}-\d{1,2}([Tt ].*)?$/.test(s)) return false;
  return true;
}

function formatScalar(v) {
  if (typeof v === 'string') return isPlainSafeScalar(v) ? v : JSON.stringify(v);
  return String(v);
}

function blockIndicator(s) {
  if (s.endsWith('\n\n')) return '|+';
  if (s.endsWith('\n')) return '|';
  return '|-';
}

function sortedKeys(map, top) {
  return Object.keys(map).sort((a, b) => {
    if (top) {
      const ia = TOP_ORDER.indexOf(a);
      const ib = TOP_ORDER.indexOf(b);
      const rankA = ia === -1 ? TOP_ORDER.length : ia;
      const rankB = ib === -1 ? TOP_ORDER.length : ib;
      if (rankA !== rankB) return rankA - rankB;
    }
    return a.localeCompare(b);
  });
}

function emitEntry(key, value, level) {
  const pad = '  '.repeat(level);
  const k = formatScalar(key);
  if (value === null || value === undefined) return [`${pad}${k}:`];
  if (Array.isArray(value)) {
    if (value.length === 0) return [`${pad}${k}: []`];
    return [`${pad}${k}:`, ...value.flatMap((item) => emitSeqItem(item, level + 1))];
  }
  if (isPlainObject(value)) {
    if (Object.keys(value).length === 0) return [`${pad}${k}: {}`];
    return [`${pad}${k}:`, ...emitMap(value, level + 1)];
  }
  if (typeof value === 'string' && value.includes('\n') && !value.includes('\t')) {
    return [`${pad}${k}: ${blockIndicator(value)}`, ...blockLines(value, level + 1)];
  }
  if (typeof value === 'string' || typeof value === 'number' || typeof value === 'boolean') {
    return [`${pad}${k}: ${formatScalar(value)}`];
  }
  throw new Error(`cannot serialize value of type ${typeof value} at key "${key}"`);
}

function blockLines(s, level) {
  const pad = '  '.repeat(level);
  return s
    .slice(0, s.endsWith('\n') ? -1 : undefined)
    .split('\n')
    .map((line) => (line === '' ? '' : pad + line));
}

function emitSeqItem(item, level) {
  const pad = '  '.repeat(level);
  const inner = '  '.repeat(level + 1);
  if (item === null || item === undefined) return [`${pad}- null`];
  if (isPlainObject(item)) {
    const keys = sortedKeys(item, false);
    if (keys.length === 0) return [`${pad}- {}`];
    const lines = [];
    keys.forEach((key, i) => {
      const sub = emitEntry(key, item[key], level + 1);
      if (i === 0) {
        lines.push(`${pad}- ${sub[0].slice(inner.length)}`, ...sub.slice(1));
      } else {
        lines.push(...sub);
      }
    });
    return lines;
  }
  if (Array.isArray(item)) {
    if (item.length === 0) return [`${pad}- []`];
    return [`${pad}-`, ...item.flatMap((v) => emitSeqItem(v, level + 1))];
  }
  if (typeof item === 'string' && item.includes('\n') && !item.includes('\t')) {
    return [`${pad}- ${blockIndicator(item)}`, ...blockLines(item, level + 1)];
  }
  if (typeof item === 'string' || typeof item === 'number' || typeof item === 'boolean') {
    return [`${pad}- ${formatScalar(item)}`];
  }
  throw new Error(`cannot serialize sequence item of type ${typeof item}`);
}

function emitMap(map, level) {
  const lines = [];
  for (const key of sortedKeys(map, level === 0)) lines.push(...emitEntry(key, map[key], level));
  return lines;
}

/** Deterministic YAML rendering: fixed top-level key order, alphabetical nested keys. */
export function emitYaml(map) {
  if (!isPlainObject(map)) throw new Error('config must be a mapping');
  return emitMap(map, 0).join('\n') + '\n';
}

/** Full generated file content: header comment + deterministic body. */
export function renderConfig(merged, { version }) {
  const lines = emitMap(merged, 0);
  return [
    `# Generated by openspec-config@${version}. Do not edit by hand.`,
    `# Source: ${REPO_URL} — rerun \`openspec-config sync\` to update.`,
    ...lines,
  ].join('\n') + '\n';
}

/** Line-based LCS diff; used by `check` to show what changed. */
export function diffLines(a, b) {
  const n = a.length;
  const m = b.length;
  const dp = Array.from({ length: n + 1 }, () => new Uint32Array(m + 1));
  for (let i = n - 1; i >= 0; i--) {
    for (let j = m - 1; j >= 0; j--) {
      dp[i][j] = a[i] === b[j] ? dp[i + 1][j + 1] + 1 : Math.max(dp[i + 1][j], dp[i][j + 1]);
    }
  }
  const out = [];
  let i = 0;
  let j = 0;
  while (i < n && j < m) {
    if (a[i] === b[j]) {
      out.push({ t: ' ', l: a[i] });
      i++;
      j++;
    } else if (dp[i + 1][j] >= dp[i][j + 1]) {
      out.push({ t: '-', l: a[i] });
      i++;
    } else {
      out.push({ t: '+', l: b[j] });
      j++;
    }
  }
  while (i < n) out.push({ t: '-', l: a[i++] });
  while (j < m) out.push({ t: '+', l: b[j++] });
  return out;
}

function readYamlFile(file) {
  const raw = readFileSync(file, 'utf8');
  try {
    return yaml.load(raw) ?? {};
  } catch (err) {
    throw new Error(`${file}: ${err.message}`);
  }
}

export function loadBase(basePath) {
  const p = basePath ?? join(PKG_ROOT, 'config', 'base.yaml');
  if (!existsSync(p)) throw new Error(`base config not found: ${p}`);
  const doc = readYamlFile(p);
  if (!isPlainObject(doc)) throw new Error(`${p}: expected a YAML mapping`);
  return doc;
}

export function pkgVersion() {
  return JSON.parse(readFileSync(join(PKG_ROOT, 'package.json'), 'utf8')).version;
}

function findOverride(openspecDir) {
  for (const name of OVERRIDE_NAMES) {
    const p = join(openspecDir, name);
    if (existsSync(p)) {
      const doc = readYamlFile(p);
      if (!isPlainObject(doc)) throw new Error(`${p}: expected a YAML mapping`);
      return doc;
    }
  }
  return {};
}

function mergedConfig(root, basePath) {
  return mergeConfigs(loadBase(basePath), findOverride(join(root, 'openspec')));
}

/**
 * Regenerate <dir>/openspec/config.yaml from the base (+ optional override).
 * Refuses to clobber a config that lacks the generated header unless --force.
 * Returns a process exit code.
 */
export function syncCommand({ dir = '.', force = false, base } = {}) {
  const root = resolve(dir);
  const openspecDir = join(root, 'openspec');
  const target = join(openspecDir, 'config.yaml');
  const rel = relative(root, target);
  const rendered = renderConfig(mergedConfig(root, base), { version: pkgVersion() });
  const existing = existsSync(target) ? readFileSync(target, 'utf8') : null;

  if (existing !== null && !GENERATED_HEADER_RE.test(existing)) {
    if (!force) {
      console.error(`${rel} exists but was not generated by openspec-config.`);
      console.error('To adopt the shared config: fold any local edits into openspec/config.override.yaml,');
      console.error('then rerun with --force.');
      return 1;
    }
  }

  if (existing === rendered) {
    console.log(`${rel} already in sync.`);
    return 0;
  }

  if (!existsSync(openspecDir)) mkdirSync(openspecDir, { recursive: true });
  writeFileSync(target, rendered);
  console.log(existing === null ? `Created ${rel}` : `Updated ${rel}`);
  return 0;
}

/**
 * Verify <dir>/openspec/config.yaml matches what sync would produce.
 * Prints a diff on mismatch. Returns a process exit code.
 */
export function checkCommand({ dir = '.', base } = {}) {
  const root = resolve(dir);
  const target = join(root, 'openspec', 'config.yaml');
  const rel = relative(root, target);
  if (!existsSync(target)) {
    console.error(`${rel} not found. Run \`openspec-config sync\` to generate it.`);
    return 1;
  }
  const existing = readFileSync(target, 'utf8');
  if (!GENERATED_HEADER_RE.test(existing)) {
    console.error(`${rel} was not generated by openspec-config (missing generated header).`);
    console.error('Adopt the shared config with `openspec-config sync --force`.');
    return 1;
  }
  const rendered = renderConfig(mergedConfig(root, base), { version: pkgVersion() });
  if (existing === rendered) {
    console.log(`${rel} is in sync.`);
    return 0;
  }
  console.error(`${rel} is out of sync with openspec-config@${pkgVersion()}:`);
  console.error('Run `openspec-config sync` and commit the result.');
  console.error(`--- ${rel}`);
  console.error('+++ generated');
  for (const d of diffLines(existing.split('\n'), rendered.split('\n'))) {
    console.error(`${d.t}${d.l}`);
  }
  return 1;
}

const HOOK_BEGIN = '# >>> openspec-config >>>';
const HOOK_END = '# <<< openspec-config <<<';
const HOOK_BLOCK = [
  HOOK_BEGIN,
  '# Installed by `openspec-config hook`: blocks commits when openspec/config.yaml is out of sync.',
  'if command -v node >/dev/null 2>&1; then',
  '  cd "$(git rev-parse --show-toplevel)" || exit 1',
  '  npx --no-install openspec-config check || {',
  '    echo "openspec/config.yaml is out of sync (or openspec-config is not installed)."',
  '    echo "Run: npx openspec-config sync"',
  '    exit 1',
  '  }',
  'fi',
  HOOK_END,
  '',
].join('\n');

function stripHookBlock(text) {
  const b = text.indexOf(HOOK_BEGIN);
  if (b === -1) return text;
  const e = text.indexOf(HOOK_END, b);
  if (e === -1) return '';
  let end = e + HOOK_END.length;
  if (text[end] === '\n') end += 1;
  return text.slice(0, b) + text.slice(end);
}

/**
 * Install (default) or remove (--remove) an openspec-config drift check in the
 * repo's pre-commit hook. Idempotent: replaces any existing block, leaves
 * surrounding hook content untouched. CI-free consistency enforcement.
 * Returns a process exit code.
 */
export function hookCommand({ dir = '.', remove = false } = {}) {
  const root = resolve(dir);
  let hookFile;
  try {
    const hooksRel = execFileSync('git', ['-C', root, 'rev-parse', '--git-path', 'hooks'], {
      encoding: 'utf8',
    }).trim();
    hookFile = resolve(root, hooksRel, 'pre-commit');
  } catch {
    console.error(`${root}: not a git repository (or git is unavailable)`);
    return 1;
  }
  mkdirSync(dirname(hookFile), { recursive: true });
  const existing = existsSync(hookFile) ? readFileSync(hookFile, 'utf8') : '';

  if (remove) {
    if (!existing.includes(HOOK_BEGIN)) {
      console.log(`No openspec-config block in ${hookFile}.`);
      return 0;
    }
    const stripped = stripHookBlock(existing);
    if (stripped.trim() === '') rmSync(hookFile);
    else writeFileSync(hookFile, stripped);
    console.log(`Removed openspec-config block from ${hookFile}.`);
    return 0;
  }

  const raw = stripHookBlock(existing);
  let base = raw.trim() === '' ? '' : raw;
  if (base !== '' && !base.endsWith('\n')) base += '\n';
  const needsShebang = base !== '' && !base.startsWith('#!');
  writeFileSync(hookFile, (needsShebang ? '#!/bin/sh\n' : '') + (base === '' ? '#!/bin/sh\n' : base) + HOOK_BLOCK);
  chmodSync(hookFile, 0o755);
  console.log(`Installed openspec-config pre-commit check in ${hookFile}`);
  return 0;
}
