import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { diffLines, emitYaml, mergeConfigs, PKG_ROOT } from '../lib/core.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const BIN = join(PKG_ROOT, 'bin', 'cli.mjs');
const BASE_FIXTURE = join(__dirname, 'fixtures', 'base.yaml');

const OVERRIDE = [
  'store: team-plans',
  'rules:',
  '  proposal:',
  '    - Keep proposals under 500 words',
  '    - Always state what is out of scope',
  '',
].join('\n');

function run(args) {
  return spawnSync(process.execPath, [BIN, ...args], { encoding: 'utf8' });
}

function mkproj(dir = tmpdir()) {
  return mkdtempSync(join(dir, 'openspec-config-'));
}

function writeOverride(dir, content = OVERRIDE) {
  mkdirSync(join(dir, 'openspec'), { recursive: true });
  writeFileSync(join(dir, 'openspec', 'config.override.yaml'), content);
}

function dataLines(content) {
  return content
    .split('\n')
    .filter((l) => l !== '' && !l.startsWith('#'));
}

test('merge: deep-merges maps, replaces scalars and arrays, deletes on null', () => {
  const base = { schema: 'spec-driven', nested: { x: 1, y: 2 }, list: [1, 2] };
  const merged = mergeConfigs(base, { nested: { y: 3 }, list: [3], gone: null, extra: true });
  assert.deepEqual(merged.nested, { x: 1, y: 3 });
  assert.deepEqual(merged.list, [3]);
  assert.equal('gone' in merged, false);
  assert.equal(merged.extra, true);
  assert.deepEqual(base.list, [1, 2]); // base is not mutated
});

test('emit: deterministic, fixed top-level order, sorted nested keys', () => {
  const doc = {
    operations: { archive: { guidance: ['Keep the summary concise'] } },
    context: 'Write all artifacts in English.\n',
    store: 'team-plans',
    rules: { proposal: ['Keep proposals under 500 words'] },
    schema: 'spec-driven',
  };
  const out = emitYaml(doc);
  assert.equal(out, emitYaml(doc)); // stable output
  const idx = (line) => dataLines(out).indexOf(line);
  assert.ok(idx('schema: spec-driven') < idx('store: team-plans'));
  assert.ok(idx('store: team-plans') < idx('context: |'));
  assert.ok(idx('context: |') < idx('rules:'));
  assert.ok(idx('rules:') < idx('operations:'));
  assert.ok(dataLines(out).includes('  Write all artifacts in English.'));
  assert.ok(dataLines(out).includes('    - Keep proposals under 500 words'));
});

test('emit: block scalar chomping indicators', () => {
  assert.equal(emitYaml({ c: 'a\n' }), 'c: |\n  a\n');
  assert.equal(emitYaml({ c: 'a\nb\n' }), 'c: |\n  a\n  b\n');
  assert.equal(emitYaml({ c: 'a\nb' }), 'c: |-\n  a\n  b\n');
  assert.equal(emitYaml({ c: 'a\n\n' }), 'c: |+\n  a\n\n');
  assert.equal(emitYaml({ c: 'a' }), 'c: a\n'); // single line needs no block
});

test('emit: quotes scalars YAML would misparse', () => {
  assert.equal(emitYaml({ a: 'true', b: 'true story', c: 42 }), 'a: "true"\nb: true story\nc: 42\n');
  assert.equal(emitYaml({ ref: '{ id: design-system, remote: "git@host:repo.git" }' }), [
    'ref: "{ id: design-system, remote: \\"git@host:repo.git\\" }"',
    '',
  ].join('\n'));
});

test('diff: line-based LCS diff', () => {
  const d = diffLines(['a', 'b', 'c'], ['a', 'x', 'c']);
  assert.equal(d.map((x) => x.t).join(''), ' -+ ');
});

test('sync: creates merged, generated config; idempotent; check passes', () => {
  const dir = mkproj();
  writeOverride(dir);
  const r = run(['sync', '--dir', dir, '--base', BASE_FIXTURE]);
  assert.equal(r.status, 0, r.stderr);
  const target = join(dir, 'openspec', 'config.yaml');
  const content = readFileSync(target, 'utf8');
  assert.match(content, /^# Generated by openspec-config@/);
  const lines = dataLines(content);
  // override: store added, rules.proposal replaced, rules.tasks preserved, context preserved
  const idx = (line) => lines.indexOf(line);
  assert.ok(lines.includes('store: team-plans'));
  assert.ok(idx('schema: spec-driven') < idx('store: team-plans') < idx('context: |') < idx('rules:'));
  assert.ok(idx('    - Keep proposals under 500 words') < idx('    - Always state what is out of scope'));
  assert.ok(idx('    - Always state what is out of scope') < idx('  tasks:'));
  assert.ok(lines.includes('    - End every task with a commit'));
  assert.ok(lines.includes('      - Run focused tests before the full suite'));
  const r2 = run(['sync', '--dir', dir, '--base', BASE_FIXTURE]);
  assert.equal(r2.status, 0, r2.stderr);
  assert.match(r2.stdout, /already in sync/);
  const r3 = run(['check', '--dir', dir, '--base', BASE_FIXTURE]);
  assert.equal(r3.status, 0, r3.stderr);
  rmSync(dir, { recursive: true, force: true });
});

test('sync: uses the shipped base by default', () => {
  const dir = mkproj();
  const r = run(['sync', '--dir', dir]);
  assert.equal(r.status, 0, r.stderr);
  const content = readFileSync(join(dir, 'openspec', 'config.yaml'), 'utf8');
  assert.match(content, /^# Generated by openspec-config@/);
  assert.ok(content.includes('schema: spec-driven'));
  rmSync(dir, { recursive: true, force: true });
});

test('sync: refuses to clobber non-generated config without --force', () => {
  const dir = mkproj();
  mkdirSync(join(dir, 'openspec'), { recursive: true });
  const handWritten = '# hand-written\nschema: spec-driven\n';
  writeFileSync(join(dir, 'openspec', 'config.yaml'), handWritten);
  const r = run(['sync', '--dir', dir, '--base', BASE_FIXTURE]);
  assert.equal(r.status, 1);
  assert.match(r.stderr, /--force/);
  assert.equal(readFileSync(join(dir, 'openspec', 'config.yaml'), 'utf8'), handWritten);
  const r2 = run(['sync', '--dir', dir, '--base', BASE_FIXTURE, '--force']);
  assert.equal(r2.status, 0, r2.stderr);
  assert.match(readFileSync(join(dir, 'openspec', 'config.yaml'), 'utf8'), /^# Generated by openspec-config@/);
  rmSync(dir, { recursive: true, force: true });
});

test('check: fails with a diff when out of sync', () => {
  const dir = mkproj();
  const r0 = run(['sync', '--dir', dir, '--base', BASE_FIXTURE]);
  assert.equal(r0.status, 0, r0.stderr);
  const target = join(dir, 'openspec', 'config.yaml');
  writeFileSync(target, readFileSync(target, 'utf8') + '# manual edit\n');
  const r = run(['check', '--dir', dir, '--base', BASE_FIXTURE]);
  assert.equal(r.status, 1);
  assert.match(r.stderr, /out of sync/);
  assert.match(r.stderr, /-# manual edit/); // present in file, absent from regenerated output
  rmSync(dir, { recursive: true, force: true });
});

test('check: fails when config is missing or not generated', () => {
  const dir = mkproj();
  const r = run(['check', '--dir', dir]);
  assert.equal(r.status, 1);
  assert.match(r.stderr, /not found/);
  mkdirSync(join(dir, 'openspec'), { recursive: true });
  writeFileSync(join(dir, 'openspec', 'config.yaml'), 'schema: spec-driven\n');
  const r2 = run(['check', '--dir', dir]);
  assert.equal(r2.status, 1);
  assert.match(r2.stderr, /--force/);
  rmSync(dir, { recursive: true, force: true });
});

test('errors: invalid YAML reports the file name', () => {
  const badBase = join(mkproj(), 'bad-base.yaml');
  writeFileSync(badBase, 'a: b: c\n');
  const dir = mkproj();
  const r = run(['sync', '--dir', dir, '--base', badBase]);
  assert.equal(r.status, 1);
  assert.match(r.stderr, /bad-base\.yaml/);
  assert.ok(!existsSync(join(dir, 'openspec', 'config.yaml')));
  rmSync(dirname(badBase), { recursive: true, force: true });
  rmSync(dir, { recursive: true, force: true });
});
